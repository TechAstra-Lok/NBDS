def process_and_seed():
    """
    Deletes existing blood banks and seeds the new comprehensive dataset.
    """
    logger.info("Starting Blood Bank Seeding Process...")
    
    # Optional: Wipe existing dataset to keep it clean. (User approved wiping)
    try:
        deleted = db.session.query(BloodBank).delete()
        logger.info(f"Deleted {deleted} existing blood bank records.")
    except Exception as e:
        logger.error(f"Error wiping data: {e}")
        db.session.rollback()
        return

    current_province = None
    count = 0
    
    for line in RAW_DATA.split('\n'):
        line = line.strip()
        if not line:
            continue
            
        if 'प्रदेश' in line:
            current_province = line
            continue
            
        # Format is: District — Name — Lat,Lng — Phone
        parts = [p.strip() for p in line.split('—')]
        if len(parts) >= 4:
            district = parts[0]
            name = parts[1]
            coords = parts[2]
            phone = parts[3]
            
            is_emergency = "(Emergency Panel)" in name
            name_clean = name.replace("(Emergency Panel)", "").strip()
            
            is_grouped = "/" in name_clean
            
            lat_str, lng_str = coords.split(',')
            lat = float(lat_str.strip())
            lng = float(lng_str.strip())
            
            maps_url = f"https://www.google.com/maps/search/?api=1&query={lat},{lng}"
            
            bank = BloodBank(
                province=current_province,
                district=district,
                name=name_clean,
                display_name=name_clean,
                latitude=lat,
                longitude=lng,
                maps_url=maps_url,
                contact_number=phone,
                is_emergency_panel=is_emergency,
                is_grouped_entry=is_grouped,
                branch_type='Emergency Center' if is_emergency else ('Grouped Branch' if is_grouped else 'Main/Sub Branch'),
                service_type='Blood Transfusion Service',
                status='active',
                is_active=True
            )
            
            db.session.add(bank)
            count += 1
            
    try:
        db.session.commit()
        logger.info(f"Successfully seeded {count} blood banks.")
    except Exception as e:
        db.session.rollback()
        logger.error(f"Failed to commit seeded data: {e}")

if __name__ == '__main__':
    # Needs to run within app context if executed directly
    from app import create_app
    app = create_app('development')
    with app.app_context():
        process_and_seed()
